//! Authoritative token registry for the BOB ecosystem: the Rust counterpart
//! of the `@gobob/tokenlist` npm package, built from the same `data/`.
//!
//! - [`TokenId`] and its subsets ([`NativeTokenId`], [`NonEvmTokenId`],
//!   [`NonEvmNativeTokenId`]) identify tokens; [`Chain`] identifies chains.
//! - [`TokenId::data`] returns a token's `data.json` contents; [`tokens`] and
//!   [`tokens_with_overrides`] iterate the entries of `tokenlist.json` and
//!   `tokenlist-overrides.json`.
//! - [`logo_uri`], [`mirror_logo_uri`], [`checksum_address`],
//!   [`to_evm_address`] and [`to_tron_address`] mirror the npm utilities.
//! - [`json`] embeds the generated JSON files verbatim.
//!
//! ```
//! use gobob_tokenlist::{tokens_with_overrides, Chain, NativeTokenId, TokenId};
//!
//! let usdc = TokenId::USDC.data();
//! assert_eq!(usdc.decimals, 6);
//!
//! let usdc_on_bob = tokens_with_overrides()
//!     .find(|token| token.token_id == TokenId::USDC && token.chain == Chain::Bob)
//!     .unwrap();
//! assert_eq!(usdc_on_bob.symbol, "USDC.e");
//! assert_eq!(usdc_on_bob.chain_id(), 60808);
//!
//! assert_eq!("BTC.b".parse::<TokenId>(), Ok(TokenId::BTC_b));
//! assert!(NativeTokenId::try_from(TokenId::ETH).is_ok());
//! ```
//!
//! # Features
//!
//! - `serde`: `Serialize`/`Deserialize` for [`Chain`] (as its `data.json`
//!   key) and the token ID types (as the token ID string).

