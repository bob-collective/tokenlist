/// Base URL of the GitHub-hosted repository files (logos, JSON lists).
pub const TOKENLIST_BASE_URL: &str =
    "https://raw.githubusercontent.com/bob-collective/tokenlist/refs/heads/main/";
/// Base URL of the BOB R2 mirror (`static.gobob.xyz`) of the repository assets.
pub const TOKENLIST_MIRROR_URL: &str = "https://static.gobob.xyz/tokenlist/";

