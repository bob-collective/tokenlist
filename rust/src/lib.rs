//! Authoritative token registry for the BOB ecosystem: the Rust counterpart
//! of the `@gobob/tokenlist` npm package, for tokens deployed on EVM chains.
//!
//! `build.rs` generates [`TokenId`] and the token table from
//! `compressedlist.json` at compile time. Lookups read static data: no I/O,
//! JSON parsing or allocation at runtime.
//!
//! A [`TokenId`] names an asset; [`TokenRegistry::on_chain`] picks its
//! [`Deployment`] on one chain, with that chain's address, decimals and
//! (UI-overridden) name and symbol.
//!
//! ```
//! use gobob_tokenlist::{TokenId, TokenRegistry};
//!
//! let usdc = TokenRegistry::get(TokenId::Usdc);
//! assert_eq!(usdc.coingecko_id, "usd-coin");
//!
//! let ethereum = TokenRegistry::on_chain(TokenId::Usdc, 1).unwrap();
//! assert_eq!(ethereum.decimals, 6);
//!
//! let bsc = TokenRegistry::on_chain(TokenId::Usdc, 56).unwrap();
//! assert_eq!(bsc.decimals, 18);
//!
//! let bob = TokenRegistry::on_chain(TokenId::Usdc, 60808).unwrap();
//! assert_eq!(bob.symbol, "USDC.e");
//!
//! let id: TokenId = "BTC+".parse().unwrap();
//! assert_eq!(id, TokenId::BtcPlus);
//! assert_eq!(id.as_str(), "BTC+");
//! ```
//!
//! Deployments on Bitcoin, Solana and Tron are not included, so tokens that
//! only exist there (`BTC`, `sBTC`, `TRX`) have no [`TokenId`].
//!
//! # Features
//!
//! - `serde`: `Serialize`/`Deserialize` for [`TokenId`] as its ID string.

#![warn(missing_docs)]

pub use alloy_primitives::Address;

// TokenId and the TOKENS table, generated by build.rs from compressedlist.json.
mod generated {
    use crate::{Deployment, TokenMetadata};

    include!(concat!(env!("OUT_DIR"), "/generated.rs"));
}

use generated::TOKENS;
pub use generated::TokenId;

/// A token: one `compressedlist.json` entry, without its non-EVM deployments.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub struct TokenMetadata {
    /// The token's ID.
    pub id: TokenId,
    /// Default name; a deployment can override it (see [`Deployment::name`]).
    pub name: &'static str,
    /// Default symbol; a deployment can override it (see [`Deployment::symbol`]).
    pub symbol: &'static str,
    /// CoinGecko API ID used for price feeds.
    pub coingecko_id: &'static str,
    /// Logo URL on GitHub (`getLogoURI` in the npm package).
    pub icon_url: &'static str,
    /// Logo URL on the BOB R2 mirror (`getMirrorLogoURI` in the npm package).
    pub mirror_icon_url: &'static str,
    /// One entry per EVM chain the token is deployed on.
    pub deployments: &'static [Deployment],
}

/// A token on one EVM chain: one `tokenlist-overrides.json` entry.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub struct Deployment {
    /// EVM chain ID.
    pub chain_id: u64,
    /// Token contract address. Native assets use the address in `data.json`:
    /// the zero address, or a system contract such as POL's `0x…1010`.
    pub address: Address,
    /// Decimals on this chain.
    pub decimals: u8,
    /// Whether the token is this chain's native asset.
    pub native: bool,
    /// Name on this chain, UI overrides applied.
    pub name: &'static str,
    /// Symbol on this chain, UI overrides applied (e.g. `USDC.e` on BOB).
    pub symbol: &'static str,
}

/// Lookups into the generated token table.
#[derive(Debug)]
pub struct TokenRegistry;

impl TokenRegistry {
    /// Every token, in [`TokenId`] order.
    pub fn all() -> &'static [TokenMetadata] {
        &TOKENS
    }

    /// The token with this ID.
    pub fn get(id: TokenId) -> &'static TokenMetadata {
        &TOKENS[id as usize]
    }

    /// The token's deployment on the chain with this ID, if any.
    pub fn on_chain(id: TokenId, chain_id: u64) -> Option<&'static Deployment> {
        Self::get(id)
            .deployments
            .iter()
            .find(|deployment| deployment.chain_id == chain_id)
    }

    /// The token deployed at this address on the chain with this ID, if any.
    pub fn by_address(
        chain_id: u64,
        address: Address,
    ) -> Option<(&'static TokenMetadata, &'static Deployment)> {
        TOKENS.iter().find_map(|token| {
            token
                .deployments
                .iter()
                .find(|deployment| deployment.chain_id == chain_id && deployment.address == address)
                .map(|deployment| (token, deployment))
        })
    }
}

impl TokenId {
    /// The token's ID string, i.e. its `data/tokens/` directory name.
    pub fn as_str(self) -> &'static str {
        self.into()
    }
}

#[cfg(feature = "serde")]
impl serde::Serialize for TokenId {
    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_str(self.as_str())
    }
}

#[cfg(feature = "serde")]
impl<'de> serde::Deserialize<'de> for TokenId {
    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        struct Visitor;

        impl serde::de::Visitor<'_> for Visitor {
            type Value = TokenId;

            fn expecting(&self, formatter: &mut std::fmt::Formatter) -> std::fmt::Result {
                formatter.write_str("a token ID")
            }

            fn visit_str<E: serde::de::Error>(self, value: &str) -> Result<TokenId, E> {
                value
                    .parse()
                    .map_err(|_| E::invalid_value(serde::de::Unexpected::Str(value), &self))
            }
        }

        deserializer.deserialize_str(Visitor)
    }
}
