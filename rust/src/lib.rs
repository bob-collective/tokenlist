//! Authoritative token registry for the BOB ecosystem: the Rust counterpart
//! of the `@gobob/tokenlist` npm package, for tokens deployed on EVM chains.
//!
//! `build.rs` generates [`ChainId`] from `supported-chains.json`, and
//! [`TokenId`] and the token data from `compressedlist.json`, at compile time.
//! The tokens are held in a `HashMap<TokenId, HashMap<ChainId,
//! TokenMetadata>>`, built on first use: each token's metadata on every EVM
//! chain it is deployed on.
//!
//! ```
//! use gobob_tokenlist::{ChainId, TokenId, TokenRegistry};
//!
//! let usdc = TokenRegistry::get(TokenId::Usdc);
//! let ethereum = &usdc[&ChainId::Ethereum];
//! assert_eq!((ethereum.chain_id, ethereum.decimals), (1, 6));
//! assert_eq!(ethereum.coingecko_id, "usd-coin");
//!
//! let bsc = TokenRegistry::on_chain(TokenId::Usdc, ChainId::BnbSmartChain).unwrap();
//! assert_eq!(bsc.decimals, 18);
//!
//! let bob = TokenRegistry::on_chain(TokenId::Usdc, ChainId::Bob).unwrap();
//! assert_eq!(bob.symbol, "USDC.e");
//!
//! let id: TokenId = "BTC+".parse().unwrap();
//! assert_eq!(id, TokenId::BtcPlus);
//! assert_eq!(id.as_str(), "BTC+");
//! assert_eq!("op-mainnet".parse(), Ok(ChainId::OpMainnet));
//! ```
//!
//! Bitcoin, Solana and Tron are not covered: they have no [`ChainId`], and
//! tokens that only exist there (`BTC`, `sBTC`, `TRX`) have no [`TokenId`].

#![warn(missing_docs)]

use std::collections::HashMap;
use std::sync::LazyLock;

pub use alloy_primitives::Address;

// ChainId, TokenId and the token data, generated by build.rs.
mod generated {
    use crate::TokenMetadata;

    include!(concat!(env!("OUT_DIR"), "/generated.rs"));
}

pub use generated::{ChainId, TokenId};

static TOKENS: LazyLock<HashMap<TokenId, HashMap<ChainId, TokenMetadata>>> =
    LazyLock::new(generated::tokens);

/// A token on one EVM chain: one `tokenlist-overrides.json` entry.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub struct TokenMetadata {
    /// The token's ID.
    pub id: TokenId,
    /// Numeric chain ID.
    pub chain_id: u64,
    /// Token contract address. Native assets use the address in `data.json`:
    /// the zero address, or a system contract such as POL's `0x…1010`.
    pub address: Address,
    /// Decimals on this chain.
    pub decimals: u8,
    /// Whether the token is this chain's native asset.
    pub native: bool,
    /// Name on this chain, UI overrides applied.
    pub name: &'static str,
    /// Symbol on this chain, UI overrides applied (e.g. `USDC.e` on BOB).
    pub symbol: &'static str,
    /// CoinGecko API ID used for price feeds.
    pub coingecko_id: &'static str,
    /// Logo URL on GitHub (`getLogoURI` in the npm package).
    pub icon_url: &'static str,
}

/// Lookups into the generated token data.
#[derive(Debug)]
pub struct TokenRegistry;

impl TokenRegistry {
    /// Every token, by ID, then by chain.
    pub fn all() -> &'static HashMap<TokenId, HashMap<ChainId, TokenMetadata>> {
        &TOKENS
    }

    /// The token with this ID, by chain. Never empty.
    pub fn get(id: TokenId) -> &'static HashMap<ChainId, TokenMetadata> {
        &TOKENS[&id]
    }

    /// The token on this chain, if deployed there: shorthand for
    /// `get(id).get(&chain)`.
    pub fn on_chain(id: TokenId, chain: ChainId) -> Option<&'static TokenMetadata> {
        Self::get(id).get(&chain)
    }
}

impl TokenId {
    /// The token's ID string, i.e. its `data/tokens/` directory name.
    pub fn as_str(self) -> &'static str {
        self.into()
    }
}

impl ChainId {
    /// The chain's `data.json` key, e.g. `"op-mainnet"`.
    pub fn as_str(self) -> &'static str {
        self.into()
    }
}
